//go:build generate

// Regenerate chinaip_data.go from the APNIC delegation statistics:
//
//	go run -tags generate chinaip_gen.go
//
// APNIC publishes the authoritative record of which ranges are delegated to
// organisations in each economy, it is refreshed daily, and unlike the
// community IPv4 lists MEOW used before it also covers IPv6.
package main

import (
	"bufio"
	"bytes"
	"encoding/binary"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"net/netip"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

const delegationURL = "https://ftp.apnic.net/stats/apnic/delegated-apnic-latest"

func main() {
	prefixes, err := fetch(delegationURL)
	if err != nil {
		log.Fatalf("fetch delegation data: %v", err)
	}

	var v4, v6 []netip.Prefix
	for _, p := range prefixes {
		if p.Addr().Is4() {
			v4 = append(v4, p)
		} else {
			v6 = append(v6, p)
		}
	}
	if len(v4) == 0 || len(v6) == 0 {
		log.Fatalf("refusing to generate a truncated table: %d IPv4 and %d IPv6 prefixes", len(v4), len(v6))
	}
	sortPrefixes(v4)
	sortPrefixes(v6)

	day := time.Now().UTC().Format("2006-01-02")
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by chinaip_gen.go; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source: %s\n", delegationURL)
	fmt.Fprintf(&buf, "// Generated: %s\n\n", day)
	fmt.Fprintf(&buf, "package main\n\n")
	fmt.Fprintf(&buf, "const cnIPDataSource = %q\n", delegationURL)
	fmt.Fprintf(&buf, "const cnIPDataGenerated = %q\n\n", day)
	writeBlock(&buf, "cnIPv4Data", v4)
	writeBlock(&buf, "cnIPv6Data", v6)

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile("chinaip_data.go", src, 0644); err != nil {
		log.Fatalf("write chinaip_data.go: %v", err)
	}
	log.Printf("wrote chinaip_data.go: %d IPv4 prefixes, %d IPv6 prefixes", len(v4), len(v6))
}

func writeBlock(buf *bytes.Buffer, name string, prefixes []netip.Prefix) {
	fmt.Fprintf(buf, "const %s = `", name)
	for i, p := range prefixes {
		if i > 0 {
			buf.WriteByte('\n')
		}
		buf.WriteString(p.String())
	}
	fmt.Fprintf(buf, "`\n\n")
}

func sortPrefixes(prefixes []netip.Prefix) {
	sort.Slice(prefixes, func(i, j int) bool {
		if c := prefixes[i].Addr().Compare(prefixes[j].Addr()); c != 0 {
			return c < 0
		}
		return prefixes[i].Bits() < prefixes[j].Bits()
	})
}

func fetch(url string) ([]netip.Prefix, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("unexpected status %s", resp.Status)
	}

	var out []netip.Prefix
	scanner := bufio.NewScanner(resp.Body)
	scanner.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		// registry|cc|type|start|value|date|status[|extensions...]
		f := strings.Split(line, "|")
		if len(f) < 7 || f[1] != "CN" {
			continue
		}
		if f[6] != "allocated" && f[6] != "assigned" {
			continue
		}
		switch f[2] {
		case "ipv4":
			ps, err := ipv4Prefixes(f[3], f[4])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", line, err)
			}
			out = append(out, ps...)
		case "ipv6":
			bits, err := strconv.Atoi(f[4])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", line, err)
			}
			addr, err := netip.ParseAddr(f[3])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", line, err)
			}
			p, err := addr.Prefix(bits)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", line, err)
			}
			out = append(out, p)
		}
	}
	return out, scanner.Err()
}

// ipv4Prefixes converts an APNIC "start address + host count" record into CIDR
// prefixes. The count is a power of two but the start is not guaranteed to be
// aligned to it, so a record can need more than one prefix to express.
func ipv4Prefixes(start, count string) ([]netip.Prefix, error) {
	addr, err := netip.ParseAddr(start)
	if err != nil {
		return nil, err
	}
	if !addr.Is4() {
		return nil, fmt.Errorf("not an IPv4 address: %s", start)
	}
	n, err := strconv.ParseUint(count, 10, 64)
	if err != nil {
		return nil, err
	}
	if n == 0 || n > 1<<32 {
		return nil, fmt.Errorf("implausible host count %s", count)
	}

	b := addr.As4()
	lo := uint64(binary.BigEndian.Uint32(b[:]))
	hi := lo + n - 1

	var out []netip.Prefix
	for lo <= hi {
		// Largest aligned block that starts at lo and does not overrun hi.
		size := uint64(1)
		for size < hi-lo+1 && lo%(size*2) == 0 && lo+size*2-1 <= hi {
			size *= 2
		}
		bits := 32
		for s := size; s > 1; s /= 2 {
			bits--
		}
		var ab [4]byte
		binary.BigEndian.PutUint32(ab[:], uint32(lo))
		out = append(out, netip.PrefixFrom(netip.AddrFrom4(ab), bits))
		lo += size
	}
	return out, nil
}
